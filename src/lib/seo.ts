/** Prefix rules for the routes that carry an id, checked before the table. */
const DYNAMIC: { test: (p: string) => boolean; meta: SeoMeta }[] = [
  {
    // The song's own screen fills these in; this is what it shows meanwhile,
    // and what a crawler gets if the songbook chunk never resolves.
    test: (p) => p.startsWith('/songs/'),
    meta: { title: 'Song', description: 'A song from the Telugu Community Church worship songbook.' }
  },
  {
    test: (p) => p.startsWith('/c/') || p.startsWith('/live/'),
    meta: {
      title: 'Live service',
      description: 'The service as it is happening.',
      noindex: true
    }
  }
]

export function seoFor(pathname: string): SeoMeta {
  const exact = ROUTE_SEO[pathname]
  if (exact) return exact
  const dynamic = DYNAMIC.find((d) => d.test(pathname))
  if (dynamic) return dynamic.meta
  // An unknown path redirects to home; describe it as home rather than leaving
  // the previous route's tags standing.
  return ROUTE_SEO['/']
}

// ------------------------------------------------------------ head writer ---
/**
 * Tags this module owns, so it can rewrite them without disturbing the ones
 * index.html sets for the installed app (theme-color, apple-* and friends).
 */
const OWNED = 'data-seo'

function upsert(tag: 'meta' | 'link', keyAttr: string, key: string, valueAttr: string, value: string): void {
  const sel = `${tag}[${keyAttr}="${key}"]`
  let el = document.head.querySelector(sel)
  if (!el) {
    el = document.createElement(tag)
    el.setAttribute(keyAttr, key)
    el.setAttribute(OWNED, '')
    document.head.appendChild(el)
  }
  el.setAttribute(valueAttr, value)
}

function applyToHead(meta: SeoMeta, pathname: string): void {
  const title = fullTitle(meta.title)
  const url = `${SITE_ORIGIN}${pathname}`
  const image = `${SITE_ORIGIN}${OG_IMAGE}`

  document.title = title
  upsert('meta', 'name', 'description', 'content', meta.description)
  upsert('link', 'rel', 'canonical', 'href', url)
  // Absent means indexable; only ever say noindex, never "index".
  upsert('meta', 'name', 'robots', 'content', meta.noindex ? 'noindex, nofollow' : 'index, follow')

  upsert('meta', 'property', 'og:type', 'content', 'website')
  upsert('meta', 'property', 'og:site_name', 'content', CHURCH.name)
  upsert('meta', 'property', 'og:title', 'content', title)
  upsert('meta', 'property', 'og:description', 'content', meta.description)
  upsert('meta', 'property', 'og:url', 'content', url)
  upsert('meta', 'property', 'og:image', 'content', image)
  upsert('meta', 'property', 'og:image:alt', 'content', `${CHURCH.name} — ${CHURCH.city}`)
  upsert('meta', 'property', 'og:locale', 'content', 'en_US')
  upsert('meta', 'property', 'og:locale:alternate', 'content', 'te_IN')

  upsert('meta', 'name', 'twitter:card', 'content', 'summary_large_image')
  upsert('meta', 'name', 'twitter:title', 'content', title)
  upsert('meta', 'name', 'twitter:description', 'content', meta.description)
  upsert('meta', 'name', 'twitter:image', 'content', image)

  // One managed JSON-LD block, replaced wholesale — merging would leave the
  // previous route's structured data describing this one.
  const existing = document.head.querySelector(`script[${OWNED}][type="application/ld+json"]`)
  if (meta.jsonLd?.length) {
    const script = existing ?? document.createElement('script')
    script.setAttribute('type', 'application/ld+json')
    script.setAttribute(OWNED, '')
    script.textContent = JSON.stringify(meta.jsonLd.length === 1 ? meta.jsonLd[0] : meta.jsonLd)
    if (!existing) document.head.appendChild(script)
  } else {
    existing?.remove()
  }
}

/**
 * Two layers, merged rather than sequenced: the route's own answer, and an
 * override from a screen that only knows its title once data has loaded. A
 * merge is used because React runs a child's effect before its parent's, so a
 * screen writing directly to the head would be overwritten by the route a
 * moment later.
 */
type Layer = 'route' | 'screen'
const layers = new Map<Layer, Partial<SeoMeta>>()
let currentPath = '/'

function flush(): void {
  const base = layers.get('route') ?? ROUTE_SEO['/']
  const over = layers.get('screen') ?? {}
  applyToHead({ ...(base as SeoMeta), ...over }, currentPath)
}

export function setRouteSeo(pathname: string): void {
  currentPath = pathname
  layers.set('route', seoFor(pathname))
  // A new route invalidates whatever the last screen said about itself.
  layers.delete('screen')
  flush()
}

export function setScreenSeo(meta: Partial<SeoMeta> | null): void {
  if (meta) layers.set('screen', meta)
  else layers.delete('screen')
  flush()
}
