import { CHURCH } from './church'

/**
 * What each route tells a crawler, a link preview and a screen reader.
 *
 * The app renders on the client and has two shells, so nothing in index.html
 * can say what a given page is — every route inherited one title and one
 * description, which is the same as having neither. This is the single place
 * that decides, and scripts/seo-audit.mjs is the thing that keeps it honest.
 *
 * Written as data rather than as tags scattered through screens because the
 * two shells render the same routes from different components: a <Seo/> in
 * MobileShell's screens and another in DesktopShell's pages would be two
 * answers to one question, and they would drift.
 */

/**
 * The one host the site is canonically served from. Deliberately a constant and
 * not window.location.origin — a canonical URL that agrees with whatever host
 * you happen to be on is a canonical URL that does nothing. Keep in step with
 * SEO_ORIGIN in scripts/seo-audit.mjs and the sitemap generator.
 */
export const SITE_ORIGIN = 'https://cantica-web.onrender.com'

/** The link-preview card. Generated by scripts/make-og.mjs. */
export const OG_IMAGE = '/og-image.png'

export interface SeoMeta {
  /** Page-specific part of the title; the church name is appended. */
  title: string
  description: string
  /** Operator tools and live surfaces — kept out of results entirely. */
  noindex?: boolean
  /** Structured data for this route, beyond the site-wide church node. */
  jsonLd?: Record<string, unknown>[]
}

const SUFFIX = ` · ${CHURCH.name}`

/**
 * Title as it appears in a tab and a result. A page title over ~60 characters is
 * truncated in a SERP, so the church name is dropped rather than the part that
 * says which page this is — a song's own name carries more than the suffix does.
 */
export function fullTitle(title: string): string {
  const withSuffix = `${title}${SUFFIX}`
  return withSuffix.length <= 60 ? withSuffix : title
}

/** The church itself, as search engines model one. */
export function churchJsonLd(): Record<string, unknown> {
  return {
    '@context': 'https://schema.org',
    '@type': 'Church',
    name: CHURCH.name,
    alternateName: CHURCH.nameTe,
    url: SITE_ORIGIN,
    logo: `${SITE_ORIGIN}/icons/pwa-512.png`,
    image: `${SITE_ORIGIN}${OG_IMAGE}`,
    description: CHURCH.welcome,
    address: {
      '@type': 'PostalAddress',
      streetAddress: '8001 Mustang Drive',
      addressLocality: 'Irving',
      addressRegion: 'TX',
      postalCode: '75038',
      addressCountry: 'US'
    },
    sameAs: [CHURCH.website],
    // The three gatherings, in the form Google reads opening hours by. A church
    // site is looked up for exactly this and nothing else surfaces it.
    openingHoursSpecification: [
      { day: 'Sunday', opens: '11:00', closes: '13:00' },
      { day: 'Wednesday', opens: '20:00', closes: '21:30' },
      { day: 'Saturday', opens: '20:00', closes: '21:30' }
    ].map((s) => ({
      '@type': 'OpeningHoursSpecification',
      dayOfWeek: `https://schema.org/${s.day}`,
      opens: s.opens,
      closes: s.closes
    })),
    event: CHURCH.services.map((s) => ({
      '@type': 'Event',
      name: s.name,
      description: s.note,
      eventAttendanceMode: s.where.startsWith('In person')
        ? 'https://schema.org/OfflineEventAttendanceMode'
        : 'https://schema.org/OnlineEventAttendanceMode',
      location: s.where.startsWith('In person')
        ? { '@type': 'Place', name: CHURCH.name, address: CHURCH.address }
        : { '@type': 'VirtualLocation', url: CHURCH.website }
    }))
  }
}

