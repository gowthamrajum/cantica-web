/**
 * Everything that has the domain baked into it, regenerated from lib/site.ts.
 *
 *   public/robots.txt      — including its Sitemap: line
 *   public/sitemap.xml     — 11 pages and one per song
 *   public/install-qr.png  — the QR shown on the projector
 *
 * These are generated rather than written because each one is a copy of the
 * origin, and copies drift. The QR is the reason this matters: it encodes the
 * URL as pixels, so a domain change leaves it pointing somewhere dead with
 * nothing to grep for and nothing that fails. A congregation scans it off a
 * screen and lands nowhere.
 *
 * The song URLs come from the same songSlug module the app routes with, so the
 * sitemap cannot advertise a URL the app would 404.
 *
 * Runs as `prebuild`, so a build cannot ship files that disagree with the
 * songbook or the domain they were built from.
 *
 *   npm run crawl-files              write them
 *   npm run crawl-files -- --check   report what would change, write nothing
 *
 * Run through `node --experimental-strip-types` because it imports .ts
 * directly. Node strips types unflagged only from 23.6; Render builds on 22,
 * where the import would otherwise throw and take the build with it.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import QRCode from 'qrcode'
import { buildSlugIndex } from '../src/lib/songSlug.ts'
import { SITE_ORIGIN } from '../src/lib/site.ts'
import songs from '../src/data/songsData.json' with { type: 'json' }

const HERE = path.dirname(fileURLToPath(import.meta.url))
const PUBLIC = path.join(HERE, '..', 'public')
const CHECK = process.argv.includes('--check')
const ORIGIN = SITE_ORIGIN.replace(/\/$/, '')

let changed = 0
function write(name, content) {
  const out = path.join(PUBLIC, name)
  const before = fs.existsSync(out) ? fs.readFileSync(out) : null
  const buf = Buffer.isBuffer(content) ? content : Buffer.from(content)
  const same = before && before.equals(buf)
  if (!same) changed++
  console.log(`  ${same ? 'same' : CHECK ? 'WOULD WRITE' : 'wrote'}  ${name.padEnd(16)} ${buf.length}B`)
  if (!same && !CHECK) fs.writeFileSync(out, buf)
}

// ------------------------------------------------------------- robots.txt ---
/**
 * The operator routes are Disallowed here AND carry a noindex meta tag. Both
 * are needed: robots.txt stops the fetch, but a page that is never crawled can
 * still be indexed from a link somewhere else, and only the meta tag prevents
 * that.
 */
const robots = `# ${'Telugu Community Church'} — ${ORIGIN}
#
# Generated by scripts/make-crawl-files.mjs from src/lib/site.ts.
# Do not edit by hand; the next build will overwrite it.
#
# Everything a visitor might search for is open. The operator tools are shut
# out here and also carry a noindex meta tag — robots.txt stops the fetch, the
# meta tag stops a link from elsewhere getting them indexed anyway.

User-agent: *
Allow: /

Disallow: /build
Disallow: /remote
Disallow: /notify
Disallow: /c/
Disallow: /live/

Sitemap: ${ORIGIN}/sitemap.xml
`

// ------------------------------------------------------------ sitemap.xml ---
/**
 * Priority is a hint about relative importance within this site, nothing more.
 * The pages answering "who are you and when do you meet" lead; the songbook
 * sits below them because it is deep, not because it is unimportant.
 *
 * The operator routes are deliberately absent — they carry noindex, and listing
 * them would be asking a crawler to fetch a page that tells it to go away.
 */
const PAGES = [
  { path: '/', priority: '1.0', changefreq: 'daily' },
  { path: '/about', priority: '0.9', changefreq: 'monthly' },
  { path: '/services', priority: '0.9', changefreq: 'monthly' },
  { path: '/visit', priority: '0.9', changefreq: 'monthly' },
  { path: '/watch', priority: '0.8', changefreq: 'weekly' },
  { path: '/give', priority: '0.7', changefreq: 'monthly' },
  { path: '/songs', priority: '0.7', changefreq: 'weekly' },
  { path: '/bible', priority: '0.7', changefreq: 'monthly' },
  { path: '/more', priority: '0.4', changefreq: 'monthly' },
  { path: '/install', priority: '0.4', changefreq: 'yearly' },
  { path: '/notifications', priority: '0.4', changefreq: 'yearly' }
]

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

const { byId } = buildSlugIndex(songs)
const songUrls = songs
  .map((s) => byId.get(s.song_id))
  .filter(Boolean)
  .sort()
  .map((slug) => ({ path: `/songs/${slug}`, priority: '0.5', changefreq: 'yearly' }))

const NS = 'http://www.sitemaps.org/schemas/sitemap/0.9'
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="${NS}">
${[...PAGES, ...songUrls]
  .map(
    (u) =>
      `  <url><loc>${esc(ORIGIN + u.path)}</loc><changefreq>${u.changefreq}</changefreq><priority>${u.priority}</priority></url>`
  )
  .join('\n')}
</urlset>
`

// ---------------------------------------------------------- install-qr.png ---
/**
 * Scanned off a projector at the back of a hall, so it is drawn large with a
 * quiet zone and high error correction — the two things that decide whether a
 * phone camera gets it from thirty feet in bad light. Navy on paper rather than
 * black on white, to match the screen it appears on.
 */
const qr = await QRCode.toBuffer(ORIGIN, {
  type: 'png',
  errorCorrectionLevel: 'H',
  width: 720,
  margin: 2,
  color: { dark: '#1b2947ff', light: '#fffdf9ff' }
})

console.log(`crawl files for ${ORIGIN}`)
write('robots.txt', robots)
write('sitemap.xml', sitemap)
write('install-qr.png', qr)
console.log(
  `${PAGES.length} pages + ${songUrls.length} songs · ${CHECK ? `${changed} would change` : `${changed} written`}`
)
